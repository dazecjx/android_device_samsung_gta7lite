def decode(b, base, count):
    """返回 [(offset, opcode, units, unit0), ...]，按真实指令边界"""
    out = []
    i = 0
    while i < count:
        u = (b[base+i*2] | (b[base+i*2+1] << 8))
        op = u & 0xff
        n = LEN.get(op, 1)
        out.append((i, op, n, u))
        i += n
    return out

def arg_regs(b, base, off, op, n):
    """对 35c/3rc 形式的 invoke 返回参数寄存器列表"""
    u = b[base+off*2] | (b[base+off*2+1] << 8)
    if op in (0x6e,0x6f,0x70,0x71,0x72,0x73,0x74,0x75,0x76,0x77,0x78,0xfc,0xfd):
        # 35c/3rc: unit0 = op(8) | G(4) | AA(4)
        g = (u >> 8) & 0xf
        a = (u >> 12) & 0xf
        w = b[base+(off+2)*2] | (b[base+(off+2)*2+1] << 8)
        c, d, e, f = w & 0xf, (w>>4)&0xf, (w>>8)&0xf, (w>>12)&0xf
        if op in (0x74,0x75,0x76,0x77,0x78,0xfd):
            start = w & 0xffff
            return list(range(start, start + a))
        return [c,d,e,f,g][:a]
    return []

def write_reg(u, op):
    """返回该指令写入的目标寄存器（若可判定），否则 None"""
